/**
 * Demo 인가 실제 운영인가
 * =======================
 *
 * 이 스위치 하나가 두 가지를 가른다.
 *
 *   1) 로그인하지 않고 직원 화면에 들어갈 수 있는가
 *   2) 사이드바에서 직원(=권한)을 바꿀 수 있는가
 *
 * 기본값은 **잠그는 쪽**이다.
 * 환경변수를 깜빡했을 때 열려 버리는 쪽으로 기울면, 잊은 그 순간이
 * 곧 사고다. 그래서 명시적으로 켜야만 Demo 가 된다.
 *
 * Demo 로 쓸 때
 * -------------
 *   NEXT_PUBLIC_DEMO_MODE=1
 *
 * 이때는 지금까지처럼 이 기기 안에서만(localStorage) 도는 가상 자료로
 * 시연·연습을 한다. 실제 고객자료는 서버에 있고 서버는 로그인해야
 * 열리므로, Demo 주소로는 실제 개인정보에 닿을 길 자체가 없다.
 *
 * 실제 운영
 * ---------
 * 변수를 넣지 않으면 그대로 운영 모드다. 로그인해야 열리고, 내가
 * 누구인지는 서버(staff.auth_user_id → role)가 정한다.
 */
export const demoMode = process.env.NEXT_PUBLIC_DEMO_MODE === "1";
