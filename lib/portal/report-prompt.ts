/**
 * 월간 웰니스 리포트 — 언어모델 연결 자리
 * ========================================
 *
 * 지금 화면에 나가는 문장은 buildReportLines() 가 규칙으로 만든다.
 * 저장된 숫자를 그대로 옮길 뿐이라 틀릴 수 없고, 인터넷이 끊겨도 나오며,
 * 호출 비용도 없다. 그래서 기본값은 규칙이다.
 *
 * 이 파일은 나중에 언어모델로 문장을 다듬고 싶어질 때를 위한 자리다.
 * 중요한 것은 모델을 붙이는 방법이 아니라 **경계를 어디에 두는가**이고,
 * 그 경계를 코드로 적어 둔다.
 *
 * 경계
 * ----
 *  - 모델에 넘기는 것은 아래 facts 뿐이다. 이름·연락처·상담메모는 넘기지 않는다.
 *  - 모델은 사실을 풀어 쓰기만 한다. 몸 상태를 판단하거나, 무엇이 좋아졌다고
 *    말하거나, 언제 오라고 권하지 않는다.
 *  - 모델 응답은 그대로 믿지 않는다. 아래 금지어가 섞여 있으면 버리고
 *    규칙으로 만든 문장을 쓴다 (fallback).
 *
 * 마지막 항목이 핵심이다. 프롬프트로 부탁하는 것과 결과를 확인하는 것은
 * 다른 일이고, 확인하지 않으면 언젠가 통과한다.
 */

import type { ReportFacts } from "./wellness";

export const REPORT_SYSTEM_PROMPT = `당신은 웰니스 매장의 고객에게 이번 달 이용 내역을 정리해 주는 도우미입니다.

반드시 지킬 것:
- 주어진 수치만 사용해 문장을 만듭니다. 주어지지 않은 값은 추측하지 않습니다.
- 몸 상태, 증상, 질환, 치료, 효과, 개선, 호전, 예방에 대해 말하지 않습니다.
- 무엇이 좋아졌다거나 나빠졌다고 판단하지 않습니다.
- 언제 방문하라고 권하지 않습니다. 사실만 적습니다.
- 앞으로의 예측, 확률, 예상 매출, 재방문 가능성을 만들지 않습니다.
- 의료적 조언을 하지 않습니다. 몸에 대한 질문은 매장에 문의하도록 안내합니다.
- 3~5문장, 존댓말, 담백하게 씁니다. 과장된 칭찬이나 권유를 넣지 않습니다.

허용되는 문장의 예:
- "최근 3개월간 총 4회 이용하셨습니다."
- "평균 이용 간격은 18일입니다."
- "최근 이용 간격은 이전보다 조금 길어졌습니다."
- "현재 이용권은 4회 남아 있습니다."`;

/** 모델에 넘기는 값 — 여기 없는 것은 넘기지 않는다 */
export function factsPayload(f: ReportFacts): Record<string, unknown> {
  return {
    기간_개월: f.months,
    기간내_이용횟수: f.visitsInPeriod,
    평균_이용간격_일: f.avgCycleDays ?? null,
    최근_이용간격_일: f.latestGapDays ?? null,
    이용권_잔여: f.remaining,
    마지막_이용일: f.lastVisitDate ?? null,
    남긴_만족도_건수: f.feedbackCount,
    남긴_만족도_평균: f.avgSatisfaction ?? null,
  };
}

/**
 * 모델이 돌려준 문장을 받아들일지 판단한다.
 *
 * 통과하지 못하면 호출한 쪽이 규칙 문장으로 되돌린다.
 * "이 정도면 괜찮겠지" 로 넘기지 않는다 — 한 번 나가면 고객이 읽는다.
 */
const BANNED =
  /(치료|치유|환자|질환|진단|처방|효능|효과가|개선|호전|완화|예방|증상|의학|권장드립니다|권해 드립니다|하셔야 합니다|예상 매출|전환율|확률)/;

export function isReportTextAcceptable(text: string): boolean {
  if (!text || text.trim().length < 10) return false;
  if (BANNED.test(text)) return false;
  // 숫자를 지어내는 흔한 형태 — % 는 이 리포트에 나올 일이 없다
  if (/\d+\s*%/.test(text)) return false;
  return true;
}
