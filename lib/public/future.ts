/**
 * 앞으로 준비하고 있는 것 — 아직 없는 기능들
 * ==============================================
 *
 * 이 파일에 적힌 다섯 가지는 **지금 쓸 수 없다.** 그게 이 파일의 존재
 * 이유다.
 *
 * 왜 아직 없는 걸 화면에 두는가
 * -----------------------------
 * 대표님이 이 화면을 보여 드릴 상대는 고객만이 아니다. 정책기관·심사자·
 * 투자자도 본다. 그분들이 알고 싶은 것은 "지금 뭐가 되나" 만이 아니라
 * "그래서 이게 어디까지 커지나" 이고, 그건 말로 설명하는 것보다 화면에
 * 자리를 잡아 두는 편이 훨씬 빠르다.
 *
 * 그런데 여기서 한 발만 잘못 디디면 거짓말이 된다.
 *
 *     그럴듯한 사진 + 그럴듯한 이름 + '가입하기' 단추
 *       = 보는 사람은 이미 있는 서비스라고 읽는다
 *
 * 그래서 세 가지를 지킨다.
 *
 *   1) 어디에나 「향후 확장」 이라고 적는다. 배지 · 색 · 문장 셋 다.
 *   2) 눌러도 아무것도 사지 못한다. 열리는 것은 설명뿐이다.
 *      '구매하기' · '가입 완료' 같은 단추를 만들지 않는다.
 *   3) 사진을 거의 쓰지 않는다. 사진이 붙는 순간 실물처럼 보인다.
 *      (홈케어만 예외 — 제품 정물이라 '준비 중' 임이 오히려 잘 드러난다)
 *
 * 그리고 순서가 중요하다. 현재 쓸 수 있는 것(예약 · 이용권 · 상담 ·
 * 내 기록)이 화면에서 **항상 먼저** 발견되어야 한다. 이 다섯은 그
 * 아래에 둔다.
 *
 * 무엇을 적었나
 * -------------
 * 다섯 가지는 지어낸 것이 아니라 매장이 실제로 가려는 방향이다.
 * Why AX 의 성장 이야기(멤버십 · 홈케어 · 추천 · 가맹 · 데이터)와
 * 같은 축을 쓴다 — 화면마다 다른 미래를 말하면 아무 미래도 못 믿는다.
 *
 * 숫자는 하나도 적지 않았다. 예상 매출 · 예상 회원 수 · 예상 지점 수는
 * 전부 확인되지 않은 값이라 적는 순간 허위가 된다.
 */

export interface FutureItem {
  key: string;
  /** 메뉴에 보이는 이름 */
  label: string;
  /** 한 줄 설명 — 목록에서 바로 보인다 */
  tagline: string;
  /** 왜 필요한가 */
  why: string;
  /** 예상 핵심 기능 3~5개 — '예상' 이라는 점을 문구에서도 지킨다 */
  features: string[];
  /** 고객에게 생기는 변화 */
  change: string;
  /** 사업적으로 어떤 의미인가 */
  growth: string;
  /** 사진을 붙일지 — 대부분 붙이지 않는다 (위 주석 3번) */
  image?: { src: string; alt: string };
}

