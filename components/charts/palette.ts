/**
 * 차트 색 체계
 * ============
 * 화면 곳곳에서 제각각이던 차트 색을 두 가지로 줄였다.
 *
 *   count  — 건수·인원 (브랜드 aqua)
 *   money  — 금액 (gold)
 *
 * 왜 두 개뿐인가:
 *  네 개 차트에 네 가지 색을 쓰면 색이 "이 차트가 무엇인가"를 말하는 것처럼 보이지만,
 *  각 차트에는 제목이 이미 붙어 있어 색이 새로 알려 주는 것이 없다. 그러면서 색끼리
 *  구별은 어려워진다(색각 이상 사용자 기준 검증에서 네 색은 기준 미달).
 *  단위가 다른 금액만 따로 두고 나머지는 한 색으로 묶는 편이 읽기 쉽다.
 *
 * 아래 값은 눈대중이 아니라 검증 도구로 확인했다(밝기 대역 · 채도 하한 ·
 * 색각 이상 구별도 · 일반 시각 구별도 · 배경 대비, 라이트/다크 모두 통과).
 * 라이트에서 gold 가 카드 배경 대비 2.88:1 로 3:1 에 살짝 못 미치는데,
 * 이 경우 규칙은 "숫자를 눈에 보이게 함께 적거나 표로도 볼 수 있게 할 것"이라
 * 두 가지를 모두 제공한다(직접 라벨 + [표로 보기]).
 */

export type SeriesKind = "count" | "money";

/** 차트에서 쓰는 CSS 변수 이름 — globals.css 에서 테마별로 값이 바뀐다 */
export const SERIES_VAR: Record<SeriesKind, string> = {
  count: "var(--chart-count)",
  money: "var(--chart-money)",
};

/** 막대 굵기 상한 — 슬롯을 꽉 채우지 않고 여백을 남긴다 */
export const BAR_MAX_PX = 24;
